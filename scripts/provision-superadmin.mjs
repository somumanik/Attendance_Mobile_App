/**
 * SuperAdmin credential provisioner (server-side bootstrap)
 * =====================================================================
 * Root cause this tool fixes: the SuperAdmin credential is intentionally NOT
 * shipped anywhere, so the server fails closed (503 "not configured") until an
 * operator provisions it. Pasting the values into .env by hand is easy to miss.
 *
 * This writes ONLY the SUPERADMIN_* keys into the (git-ignored) server .env,
 * leaving every other line untouched. The password itself is never written to
 * disk — only its scrypt hash + salt go into .env.
 *
 * Usage (from the repo root):
 *   node scripts/provision-superadmin.mjs                      # random strong password
 *   node scripts/provision-superadmin.mjs <username>           # custom username
 *   node scripts/provision-superadmin.mjs <username> "<password>"   # choose the password
 *
 * After running, restart the API server so it re-reads .env.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const ENV_PATH = path.join(ROOT, '.env');

const auth = await import(pathToFileURL(path.join(ROOT, 'server', 'superadmin-auth.js')).href);

const username = (process.argv[2] || 'superadmin').trim();
const chosen = process.argv[3] || null;

if (!username) {
  console.error('Username must not be empty.');
  process.exit(1);
}
if (chosen && chosen.length < 8) {
  console.error('Password must be at least 8 characters.');
  process.exit(1);
}

/** A unique random bootstrap secret — never a fixed/default value. */
const password = chosen || crypto.randomBytes(15).toString('base64url');
const { hash, salt, algo } = await auth.hashSuperAdminPassword(password);

if (!fs.existsSync(ENV_PATH)) {
  console.error('Missing .env — create it from .env.example first.');
  process.exit(1);
}

const raw = fs.readFileSync(ENV_PATH, 'utf8');
const eol = raw.includes('\r\n') ? '\r\n' : '\n';
const lines = raw.split(/\r?\n/).filter((line) => !/^\s*SUPERADMIN_/.test(line));
while (lines.length && lines[lines.length - 1].trim() === '') lines.pop();

const block = [
  '',
  '# SuperAdmin (separate management role) — generated by scripts/provision-superadmin.mjs',
  '# Only the hash is stored; the plaintext password is never written to disk.',
  `SUPERADMIN_USERNAME=${username}`,
  `SUPERADMIN_PASSWORD_HASH=${hash}`,
  `SUPERADMIN_PASSWORD_SALT=${salt}`,
  `SUPERADMIN_PASSWORD_ALGO=${algo}`,
];

fs.writeFileSync(ENV_PATH, `${lines.join(eol)}${eol}${block.join(eol)}${eol}`, 'utf8');

console.log('');
console.log('SuperAdmin credential provisioned into .env (git-ignored).');
console.log('Restart the API server so it re-reads the environment.');
console.log('');
console.log('  Username : ' + username);
console.log('  Password : ' + password + '    <-- shown ONCE, store it in your password manager');
console.log('');
console.log('Rotate any time with:  node scripts/provision-superadmin.mjs ' + username + ' "<new-password>"');
console.log('');
